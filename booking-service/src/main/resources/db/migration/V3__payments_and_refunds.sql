CREATE TABLE payment
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id         BIGINT         NOT NULL REFERENCES booking (id),
    idempotency_key    VARCHAR(100)   NOT NULL,
    payment_token      VARCHAR(255)   NOT NULL,
    amount             NUMERIC(38, 2) NOT NULL,
    currency           VARCHAR(255)   NOT NULL,
    status             VARCHAR(255)   NOT NULL,
    provider_reference VARCHAR(255)   NOT NULL,
    created_at         TIMESTAMP      NOT NULL,
    UNIQUE (booking_id, idempotency_key)
);
CREATE UNIQUE INDEX payment_one_success ON payment (booking_id) WHERE status IN ('SUCCEEDED', 'REFUNDED');
CREATE TABLE refund
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id         BIGINT         NOT NULL UNIQUE REFERENCES payment (id),
    booking_id         BIGINT         NOT NULL UNIQUE REFERENCES booking (id),
    amount             NUMERIC(38, 2) NOT NULL,
    currency           VARCHAR(255)   NOT NULL,
    status             VARCHAR(255)   NOT NULL,
    provider_reference VARCHAR(255)   NOT NULL,
    created_at         TIMESTAMP      NOT NULL
);
