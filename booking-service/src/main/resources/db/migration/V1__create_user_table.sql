CREATE TABLE show
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id        BIGINT         NOT NULL,
    theatre_id      BIGINT         NOT NULL,
    show_time       TIMESTAMP      NOT NULL,
    end_time        TIMESTAMP      NOT NULL,
    total_seats     INTEGER        NOT NULL,
    available_seats INTEGER        NOT NULL,
    base_price      NUMERIC(38, 2) NOT NULL,
    status          VARCHAR(255)   NOT NULL
);
CREATE TABLE seat_inventory
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id     BIGINT           NOT NULL REFERENCES show (id),
    seat_number VARCHAR(255)     NOT NULL,
    price       DOUBLE PRECISION NOT NULL,
    seat_status VARCHAR(255)     NOT NULL,
    UNIQUE (show_id, seat_number)
);
CREATE TABLE booking
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR(255) UNIQUE NOT NULL,
    user_id           BIGINT              NOT NULL,
    show_id           BIGINT              NOT NULL REFERENCES show (id),
    status            VARCHAR(255)        NOT NULL,
    base_amount       NUMERIC(38, 2),
    discount_amount   NUMERIC(38, 2),
    final_amount      NUMERIC(38, 2),
    booking_time      TIMESTAMP,
    expiry_time       TIMESTAMP
);
CREATE TABLE booking_seat
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id        BIGINT NOT NULL REFERENCES booking (id),
    seat_inventory_id BIGINT NOT NULL REFERENCES seat_inventory (id),
    seat_number       VARCHAR(255),
    price_paid        DOUBLE PRECISION,
    status            VARCHAR(255)
);
CREATE TABLE outbox_events
(
    event_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(255),
    aggregate_id   VARCHAR(255),
    event_type     VARCHAR(255),
    payload        VARCHAR(255),
    event_status   VARCHAR(255),
    status         VARCHAR(255),
    created_at     TIMESTAMP,
    processed_at   TIMESTAMP
);
CREATE INDEX booking_expiry_idx ON booking (status, expiry_time);
CREATE INDEX booking_user_idx ON booking (user_id);
CREATE INDEX outbox_pending_idx ON outbox_events (event_status, event_id);
