ALTER TABLE auth.app_user
    ADD COLUMN email VARCHAR(254) UNIQUE;
-- Legacy accounts have no email; preserve their existing access during migration.
ALTER TABLE auth.app_user
    ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT true;
CREATE TABLE auth.account_action
(
    token_hash  VARCHAR(64) PRIMARY KEY,
    username    VARCHAR(64) NOT NULL REFERENCES auth.app_user (username),
    purpose     VARCHAR(20) NOT NULL CHECK (purpose IN ('VERIFY_EMAIL', 'RESET_PASSWORD')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at  TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ
);
CREATE INDEX account_action_user ON auth.account_action (username, purpose);
CREATE TABLE auth.mail_key
(
    id     INTEGER PRIMARY KEY,
    secret TEXT NOT NULL
);
CREATE TABLE auth.mail_outbox
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient      VARCHAR(254) NOT NULL,
    subject        VARCHAR(255) NOT NULL,
    encrypted_body TEXT,
    status         VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    attempts       INTEGER      NOT NULL DEFAULT 0,
    next_attempt   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX mail_outbox_pending ON auth.mail_outbox (status, next_attempt);
